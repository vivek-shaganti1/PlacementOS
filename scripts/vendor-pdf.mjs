// Builds api/_vendor/pdf.js: the PDF text reader (unpdf, which wraps pdf.js) and an inflater (fflate) as one minified file with no imports.
// Vercel uploads a function's packages un-minified, which puts this one at the edge size limit.
//   node scripts/vendor-pdf.mjs           rebuild (after changing the unpdf version)
//   node scripts/vendor-pdf.mjs --check   fail if the committed file is not what the installed version builds (CI)
import { build } from 'esbuild'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { gzipSync } from 'node:zlib'

const out = 'api/_vendor/pdf.js'
const result = await build({
  stdin: { contents: "export { extractText, getDocumentProxy } from 'unpdf'; export { Inflate } from 'fflate'", resolveDir: process.cwd(), loader: 'js' },
  bundle: true, minify: true, format: 'esm', platform: 'neutral', mainFields: ['module', 'main'], target: 'es2022',
  define: { 'import.meta.url': '"https://placementiq.invalid/pdf.js"' },
  legalComments: 'inline', write: false, metafile: true, logLevel: 'warning',
})
const external = Object.values(result.metafile.outputs).flatMap((o) => o.imports)
if (external.length) throw new Error(`Not self-contained: ${external.map((i) => i.path).join(', ')}`)
const code = `// Generated by scripts/vendor-pdf.mjs from unpdf (MIT), fflate (MIT) and pdf.js (Apache-2.0). Do not edit.\n${result.outputFiles[0].text}`
const gz = gzipSync(code).length
if (gz > 700_000) throw new Error(`Too large for an edge function: ${gz} bytes compressed`)
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== code) throw new Error(`${out} is out of date: run node scripts/vendor-pdf.mjs`)
  console.log(`${out} is up to date (${gz} bytes compressed)`)
} else {
  mkdirSync('api/_vendor', { recursive: true })
  writeFileSync(out, code)
  console.log(`${out}: ${gz} bytes compressed`)
}

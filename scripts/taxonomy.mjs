// Draws the engineering tree (src/data/engineering) into its README, from the data itself, so the map cannot drift.
//   node scripts/taxonomy.mjs           rewrite src/data/engineering/README.md
//   node scripts/taxonomy.mjs --check   fail if the README is out of date (CI)
import { buildSync } from 'esbuild'
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

const out = join(mkdtempSync(join(tmpdir(), 'taxonomy-')), 'engineering.mjs')
buildSync({ entryPoints: ['src/data/engineering/index.ts'], bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error' })
const { FAMILIES, TRACKS, SKILL_RULES } = await import(pathToFileURL(out).href)

const folder = { lifesci: 'life-sciences' }
const short = new Map(SKILL_RULES.map((s) => [s.name, s.short]))
const lines = []
lines.push('Engineering')
FAMILIES.forEach((f, fi) => {
  const lastF = fi === FAMILIES.length - 1
  const p = lastF ? '    ' : '│   '
  lines.push(`${lastF ? '└──' : '├──'} ${f.label}  (${folder[f.id] ?? f.id}/)`)
  lines.push(`${p}├── Branches: ${f.branches.map((b) => b.code).join(', ')}`)
  lines.push(`${p}└── Tracks (starts on: ${f.defaultTracks.join(', ')})`)
  f.tracks.forEach((t, ti) => {
    const lastT = ti === f.tracks.length - 1
    const q = `${p}    ${lastT ? '    ' : '│   '}`
    lines.push(`${p}    ${lastT ? '└──' : '├──'} ${t.label}  [${t.id}]  open to: ${t.families.join(', ')}`)
    t.roles.forEach((r, ri) => lines.push(`${q}${ri === t.roles.length - 1 ? '└──' : '├──'} ${r.title}: ${r.skills.map((s) => short.get(s) ?? s).join(', ')}`))
  })
})

const readme = `# The engineering tree

Generated by \`node scripts/taxonomy.mjs\` from the files in this folder; CI fails if it is out of date. Edit the files, not
this map.

**Levels:** Engineering → family → branch (as colleges spell it) → career track → job role → skills. A student's branch
picks the family, the family offers tracks (a student chooses up to three; software is open to every branch), each track
lists the skills it is measured on, and each role names the skills of its track it leans on most.

**Folders:** one folder per family; inside it \`branches/\` (one file per branch, with the pattern that recognises how
colleges write it) and \`tracks/\` (one file per career track, with its roles). \`skills/\` holds every skill and the evidence
that can prove it; \`evidence.ts\` the file types, ignored paths and GATE papers; \`index.ts\` puts the tree together.

Roles are the jobs graduates of a track are usually hired into. They are general career knowledge, not any company's
requirements; a company's real criteria come from its drives and from checked sources.

\`\`\`text
${lines.join('\n')}
\`\`\`

${FAMILIES.reduce((a, f) => a + f.branches.length, 0)} branches, ${TRACKS.length} tracks, ${TRACKS.reduce((a, t) => a + t.roles.length, 0)} roles, ${SKILL_RULES.length} skills.
`
const file = 'src/data/engineering/README.md'
if (process.argv.includes('--check')) {
  let now = ''
  try { now = readFileSync(file, 'utf8') } catch {}
  if (now !== readme) {
    console.error(`${file} is out of date: run node scripts/taxonomy.mjs`)
    process.exit(1)
  }
  console.log(`${file} matches the tree`)
} else {
  writeFileSync(file, readme)
  console.log(`wrote ${file}`)
}
